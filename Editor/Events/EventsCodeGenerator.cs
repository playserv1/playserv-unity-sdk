        private static FieldInfo? GetSinglePublicInstanceField(Type type)
        {
            var fields = type
                .GetFields(BindingFlags.Instance | BindingFlags.Public)
                .Where(f => !f.IsStatic)
                .ToArray();

            if (fields.Length != 1)
                return null;

            return fields[0];
        }

        private static Dictionary<Type, string> BuildMethodSuffixMap(TypeCache.TypeCollection eventTypes)
        {
            var types = eventTypes
                .Distinct()
                .ToArray();

            var suffixMap = new Dictionary<Type, string>();

            foreach (var group in types.GroupBy(t => t.Name, StringComparer.Ordinal))
            {
                if (group.Count() == 1)
                {
                    var type = group.First();
                    suffixMap[type] = SanitizeIdentifierPart(type.Name);
                    continue;
                }

                var usedSuffixes = new HashSet<string>(StringComparer.Ordinal);

                foreach (var type in group.OrderBy(t => t.FullName, StringComparer.Ordinal))
                {
                    var suffix = BuildQualifiedMethodSuffix(type);
                    if (!usedSuffixes.Add(suffix))
                    {
                        var fallbackBase = BuildCollisionFallbackMethodSuffix(type);
                        suffix = fallbackBase;

                        var counter = 2;
                        while (!usedSuffixes.Add(suffix))
                        {
                            suffix = $"{fallbackBase}_{counter}";
                            counter++;
                        }
                    }

                    suffixMap[type] = suffix;
                }
            }

            return suffixMap;
        }

        private static string BuildQualifiedMethodSuffix(Type type)
        {
            var parts = new List<string>();

            if (!string.IsNullOrWhiteSpace(type.Namespace))
            {
                parts.AddRange(type.Namespace
                    .Split('.')
                    .Select(SanitizeIdentifierPart)
                    .Where(part => part.Length > 0));
            }

            foreach (var declaringType in GetDeclaringTypes(type))
                parts.Add(SanitizeIdentifierPart(declaringType.Name));

            parts.Add(SanitizeIdentifierPart(type.Name));

            var suffix = string.Join("_", parts.Where(part => part.Length > 0));
            return string.IsNullOrWhiteSpace(suffix) ? "Event" : suffix;
        }

        private static string BuildCollisionFallbackMethodSuffix(Type type)
        {
            var identity = type.FullName ?? type.AssemblyQualifiedName ?? type.Name;
            var sanitizedIdentity = SanitizeIdentifierPart(identity);
            var hash = ComputeStableHash(identity);
            return $"{sanitizedIdentity}_{hash}";
        }

        private static IEnumerable<Type> GetDeclaringTypes(Type type)
        {
            var declaringTypes = new Stack<Type>();
            var current = type.DeclaringType;

            while (current != null)
            {
                declaringTypes.Push(current);
                current = current.DeclaringType;
            }

            return declaringTypes;
        }

        private static string SanitizeIdentifierPart(string value)
        {
            if (string.IsNullOrWhiteSpace(value))
                return string.Empty;

            var sb = new StringBuilder(value.Length);
            var previousWasUnderscore = false;

            foreach (var ch in value)
            {
                if (char.IsLetterOrDigit(ch) || ch == '_')
                {
                    sb.Append(ch);
                    previousWasUnderscore = false;
                    continue;
                }

                if (!previousWasUnderscore)
                {
                    sb.Append('_');
                    previousWasUnderscore = true;
                }
            }

            var sanitized = sb.ToString().Trim('_');
            if (string.IsNullOrWhiteSpace(sanitized))
                return string.Empty;

            if (char.IsDigit(sanitized[0]))
                sanitized = "_" + sanitized;

            return sanitized;
        }

        private static string ComputeStableHash(string value)
        {
            unchecked
            {
                var hash = 2166136261u;

                foreach (var ch in value)
                {
                    hash ^= ch;
                    hash *= 16777619u;
                }

                return hash.ToString("x8");
            }
        }

        private static string ToCamel(string s)
        {
            if (string.IsNullOrWhiteSpace(s))
                return s;

            if (s.Length == 1)
                return char.ToLowerInvariant(s[0]).ToString();

            return char.ToLowerInvariant(s[0]) + s.Substring(1);
        }

        private static string GetCSharpTypeName(Type type)
        {
            if (type.IsByRef)
                return GetCSharpElementTypeName(type);

            if (type.IsPointer)
                return $"{GetCSharpElementTypeName(type)}*";

            if (type.IsArray)
            {
                var rankSuffix = type.GetArrayRank() == 1
                    ? string.Empty
                    : new string(',', type.GetArrayRank() - 1);
                return $"{GetCSharpElementTypeName(type)}[{rankSuffix}]";
            }

            if (type.IsGenericParameter)
                return type.Name;

            if (!type.IsGenericType)
                return GetCSharpNonGenericTypeName(type);

            var typeDefName = StripGenericArity(GetCSharpNonGenericTypeName(type.GetGenericTypeDefinition()));

            var genericArgs = type.GetGenericArguments()
                .Select(GetCSharpTypeName)
                .ToArray();

            return $"{typeDefName}<{string.Join(", ", genericArgs)}>";
        }

        private static string GetCSharpElementTypeName(Type type)
        {
            var elementType = type.GetElementType();
            return elementType == null
                ? "global::System.Object"
                : GetCSharpTypeName(elementType);
        }

        private static string GetCSharpNonGenericTypeName(Type type)
        {
            var declaringTypes = GetDeclaringTypes(type).ToArray();
            var rootType = declaringTypes.Length > 0 ? declaringTypes[0] : type;

            var typeParts = declaringTypes
                .Select(declaringType => StripGenericArity(declaringType.Name))
                .Concat(new[] { StripGenericArity(type.Name) })
                .Where(part => !string.IsNullOrWhiteSpace(part));

            var localTypeName = string.Join(".", typeParts);
            if (string.IsNullOrWhiteSpace(rootType.Namespace))
                return $"global::{localTypeName}";

            return $"global::{rootType.Namespace}.{localTypeName}";
        }

        private static string StripGenericArity(string typeName)
        {
            if (string.IsNullOrWhiteSpace(typeName))
                return string.Empty;

            var tickIndex = typeName.IndexOf('`');
            return tickIndex >= 0
                ? typeName.Substring(0, tickIndex)
                : typeName;
        }

        private static void WriteFile(string assetPath, string content)
        {
            var fullPath = Path.GetFullPath(assetPath);
            var directory = Path.GetDirectoryName(fullPath);
            if (!Directory.Exists(directory))
                Directory.CreateDirectory(directory);

            if (File.Exists(fullPath))
            {
                var existing = File.ReadAllText(fullPath);
                if (string.Equals(existing, content, StringComparison.Ordinal))
                    return;
            }

            WriteAllText(fullPath, content, Encoding.UTF8);
        }
