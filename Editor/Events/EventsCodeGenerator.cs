        public static void Generate()
        {
            var changed = SyncGeneratedOutputForCurrentState();
            if (changed)
                AssetDatabase.Refresh();
        }

        public static bool SyncGeneratedOutputForCurrentState()
        {
            if (!CanGenerateEvents())
                return GenerateDisabledOutput();

            var eventTypes = TypeCache.GetTypesWithAttribute<EventAttribute>()
                .Where(IsGeneratedOutputEventType)
                .OrderBy(GetStableTypeIdentity, StringComparer.Ordinal)
                .ToArray();
            var changed = false;

            changed |= GenerateApiExtensionsCode(eventTypes);
            changed |= GenerateAdapterExtensionsCode(eventTypes);

            return changed;
        }

        private static bool CanGenerateEvents()
        {
            var state = Playserv.Editor.PlayServRuntimeModuleDefines.Load();
            Playserv.Editor.PlayServEditorModuleAvailability.NormalizeAvailableRuntimeState(state);
            Playserv.Editor.PlayServRuntimeModuleDefines.NormalizeDependencies(state);
            return state.IsEnabled(PlayServModuleManifest.EventsId) &&
                   Playserv.Editor.PlayServEditorModuleAvailability.EditorEvents;
        }

        private static bool IsGeneratedOutputEventType(Type type)
        {
            if (type == null)
                return false;

            var assemblyName = type.Assembly.GetName().Name;
            if (string.Equals(assemblyName, PackageSamplesAssemblyName, StringComparison.Ordinal))
                return false;

            var typeNamespace = type.Namespace ?? string.Empty;
            return !string.Equals(typeNamespace, PackageSamplesNamespace, StringComparison.Ordinal) &&
                   !typeNamespace.StartsWith(PackageSamplesNamespace + ".", StringComparison.Ordinal);
        }

        private static bool GenerateDisabledOutput()
        {
            var changed = false;
            changed |= WriteFile(ApiExtensionsOutputPath, GenerateDisabledApiExtensionsCode());
            changed |= WriteFile(AdapterExtensionsOutputPath, GenerateDisabledAdapterExtensionsCode());
            return changed;
        }

