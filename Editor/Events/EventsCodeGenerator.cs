        private static bool GenerateApiExtensionsCode(IEnumerable<Type> eventTypes)
        {
            var orderedEventTypes = OrderEventTypes(eventTypes).ToArray();
            var methodSuffixMap = BuildMethodSuffixMap(orderedEventTypes);
            var generationHash = ComputeGenerationHash(orderedEventTypes, methodSuffixMap, "api");
            if (IsGeneratedFileCurrent(ApiExtensionsOutputPath, generationHash))
                return false;

            var sb = new StringBuilder();

            sb.AppendLine("// <auto-generated />");
            sb.AppendLine($"{GeneratedHashPrefix}{generationHash}>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("using System;");
            sb.AppendLine("using Playserv.Events;");
            sb.AppendLine("using Playserv.Wrapper;"); // IPlayServEventsApi lives here in your setup
            sb.AppendLine();
            sb.AppendLine("namespace Playserv.Wrapper");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// Generated convenience methods for events based on [Event] types.");
            sb.AppendLine("    /// Extensions on IPlayServEventsApi.");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine("    public static class PlayServEventsApiExtensions");
            sb.AppendLine("    {");

            foreach (var type in orderedEventTypes)
            {
                if (!TryGetEventType(type, out var eventType))
                    continue;

                if ((eventType & EventTypeGlobal) != 0)
                    AppendApiGlobalEventMethods(sb, type, methodSuffixMap[type]);

                if ((eventType & EventTypeGroup) != 0)
                    AppendApiGroupEventMethods(sb, type, methodSuffixMap[type]);

                if ((eventType & EventTypeUser) != 0)
                    AppendApiUserEventMethods(sb, type, methodSuffixMap[type]);
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine("#nullable restore");

            return WriteFile(ApiExtensionsOutputPath, sb.ToString());
        }

        private static bool GenerateAdapterExtensionsCode(IEnumerable<Type> eventTypes)
        {
            var orderedEventTypes = OrderEventTypes(eventTypes).ToArray();
            var methodSuffixMap = BuildMethodSuffixMap(orderedEventTypes);
            var generationHash = ComputeGenerationHash(orderedEventTypes, methodSuffixMap, "adapter");
            if (IsGeneratedFileCurrent(AdapterExtensionsOutputPath, generationHash))
