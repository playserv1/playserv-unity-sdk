                if ((eventType & EventTypeGlobal) != 0)
                    AppendAdapterGlobalEventMethods(sb, type, methodSuffixMap[type]);

                if ((eventType & EventTypeGroup) != 0)
                    AppendAdapterGroupEventMethods(sb, type, methodSuffixMap[type]);

                if ((eventType & EventTypeUser) != 0)
                    AppendAdapterUserEventMethods(sb, type, methodSuffixMap[type]);
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine("#nullable restore");

            return WriteFile(AdapterExtensionsOutputPath, sb.ToString());
        }

        private static bool TryGetEventType(Type type, out int eventType)
        {
            eventType = EventTypeAll;
            var attribute = type
                .GetCustomAttributes(typeof(EventAttribute), inherit: false)
                .OfType<EventAttribute>()
                .FirstOrDefault();

            if (attribute == null)
                return false;

            eventType = (int)attribute.Type;
            return true;
        }

