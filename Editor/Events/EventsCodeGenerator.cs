            sb.AppendLine("    /// Generated adapter extensions based on [Event] types.");
            sb.AppendLine("    /// Useful if you work with IEventsAdapter directly.");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine("    public static class EventsAdapterExtensions");
            sb.AppendLine("    {");

