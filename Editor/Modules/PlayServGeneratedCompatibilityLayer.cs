    internal static class PlayServGeneratedCompatibilityLayer
    {
        private const string ThisScriptSuffix = "/Editor/Modules/PlayServGeneratedCompatibilityLayer.cs";
        private const string CompatibilityRelativePath = "Runtime/Generated/Compatibility/PlayServCompatibility.g.cs";
        private const string ModuleRegistryRelativePath = "Runtime/Generated/Modules/PlayServModuleRegistry.g.cs";
        private const string GeneratedEventsApiExtensionsAssetPath = "Assets/Shared/Generated/Events/PlayServ.EventsApiExtensions.g.cs";
        private const string GeneratedEventsAdapterExtensionsAssetPath = "Assets/Shared/Generated/Events/EventsAdapterExtensions.g.cs";

        private static PlayServPackageRoot _packageRoot;

        public static void SyncNow()
        {
            PlayServModuleGraphSynchronizer.SyncNow();
        }

        internal static void SyncNow(bool refreshAssetDatabase)
        {
            PlayServModuleGraphSynchronizer.SyncNow(refreshAssetDatabase);
        }

        internal static bool SyncGeneratedFiles(PlayServRuntimeModuleState runtimeState, bool importAssets)
        {
            var context = PlayServModuleCodegenRegistry.Build(runtimeState);
            var changed = false;

            changed |= WriteIfChanged(CompatibilityRelativePath, GenerateCompatibility(context), importAssets);
            changed |= WriteIfChanged(ModuleRegistryRelativePath, GenerateModuleRegistry(context), importAssets);
            changed |= SyncGeneratedEventsOutput(importAssets);

            return changed;
        }

        private static bool SyncGeneratedEventsOutput(bool importAssets)
        {
            if (!PlayServGeneratedEventsOutputRegistry.TrySync(out var changed))
                return SyncDisabledGeneratedEventsOutput(importAssets);

            return changed;
        }

        private static bool SyncDisabledGeneratedEventsOutput(bool importAssets)
        {
            var changed = false;
            changed |= WriteAssetPathIfChanged(GeneratedEventsApiExtensionsAssetPath, GenerateDisabledEventsApiExtensionsCode(), importAssets);
            changed |= WriteAssetPathIfChanged(GeneratedEventsAdapterExtensionsAssetPath, GenerateDisabledEventsAdapterExtensionsCode(), importAssets);
            return changed;
        }

        private static string GenerateDisabledEventsApiExtensionsCode()
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("namespace Playserv.Wrapper");
            sb.AppendLine("{");
            sb.AppendLine("    public static class PlayServEventsApiExtensions");
            sb.AppendLine("    {");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine("#nullable restore");
            return sb.ToString();
        }

        private static string GenerateDisabledEventsAdapterExtensionsCode()
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("namespace Playserv.Events");
            sb.AppendLine("{");
            sb.AppendLine("    public static class EventsAdapterExtensions");
            sb.AppendLine("    {");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine("#nullable restore");
            return sb.ToString();
        }

        private static string GenerateCompatibility(PlayServModuleCodegenContext context)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");

            var usings = new List<string>(context.CompatibilityUsings);
            if (context.HasLocalExecutionFactory)
            {
                AddUnique(usings, "System");
                AddUnique(usings, "Playserv.Proxy.Common");
            }

            usings.Sort(StringComparer.Ordinal);
            for (var i = 0; i < usings.Count; i++)
                sb.Append("using ").Append(usings[i]).AppendLine(";");

            if (usings.Count > 0)
                sb.AppendLine();

            sb.AppendLine("namespace Playserv.Wrapper");
            sb.AppendLine("{");
            AppendPlayServFacade(sb, context.FacadeMembers);

            if (context.HasLocalExecutionFactory)
            {
                sb.AppendLine();
                AppendLocalExecutionDispatch(sb, context.LocalExecutionFactoryExpression);
            }

            sb.AppendLine("}");
            return sb.ToString();
        }

        private static void AppendPlayServFacade(StringBuilder sb, IReadOnlyList<string[]> facadeMembers)
        {
            sb.AppendLine("    public static partial class PlayServ");
            sb.AppendLine("    {");

            for (var i = 0; i < facadeMembers.Count; i++)
            {
                if (i > 0)
                    sb.AppendLine();

                AppendIndentedLines(sb, facadeMembers[i], "        ");
            }

            sb.AppendLine("    }");
        }

        private static void AppendLocalExecutionDispatch(StringBuilder sb, string factoryExpression)
        {
            sb.AppendLine("    internal static partial class PlayServCommandDispatchFactory");
            sb.AppendLine("    {");
            sb.AppendLine("        static partial void TryCreateModuleDispatch(ref IPlayServCommandDispatch dispatch)");
            sb.AppendLine("        {");
            sb.AppendLine("            var localExecution = CreateLocalExecution();");
            sb.AppendLine("            if (localExecution != null)");
            sb.AppendLine("                dispatch = new PlayServLocalExecutionCommandDispatch(localExecution);");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        private static ILocalCommandExecution CreateLocalExecution()");
            sb.AppendLine("        {");
            sb.Append("            return ").Append(factoryExpression).AppendLine(";");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine("    internal sealed class PlayServLocalExecutionCommandDispatch : IPlayServCommandDispatch");
            sb.AppendLine("    {");
            sb.AppendLine("        private readonly ILocalCommandExecution _localExecution;");
            sb.AppendLine();
            sb.AppendLine("        public PlayServLocalExecutionCommandDispatch(ILocalCommandExecution localExecution)");
            sb.AppendLine("        {");
            sb.AppendLine("            _localExecution = localExecution ?? throw new ArgumentNullException(nameof(localExecution));");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        public object LocalExecution => _localExecution;");
            sb.AppendLine();
            sb.AppendLine("        public bool TryHandleCommand<T>(T command, string moduleName, bool hasRuntimeInstance)");
            sb.AppendLine("        {");
            sb.AppendLine("            return _localExecution.TryHandleCommand(command, moduleName, hasRuntimeInstance);");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
        }

        private static string GenerateModuleRegistry(PlayServModuleCodegenContext context)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("using System;");
            sb.AppendLine();
            sb.AppendLine("namespace Playserv.Modules");
            sb.AppendLine("{");
            sb.AppendLine("    public static partial class PlayServModuleRegistry");
            sb.AppendLine("    {");
            sb.AppendLine("        static partial void RegisterGenerated(PlayServModuleHost host)");
            sb.AppendLine("        {");

            for (var i = 0; i < context.RuntimeRegistrations.Count; i++)
            {
                var registration = context.RuntimeRegistrations[i];
                sb.Append("            RegisterManifestModule(host, ")
                    .Append(QuoteCSharpString(registration.ModuleId))
                    .Append(", () => new global::")
                    .Append(registration.RuntimeModuleTypeName)
                    .AppendLine("());");
            }

            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        private static void RegisterManifestModule(");
            sb.AppendLine("            PlayServModuleHost host,");
            sb.AppendLine("            string moduleId,");
            sb.AppendLine("            Func<IPlayServModule> factory)");
            sb.AppendLine("        {");
            sb.AppendLine("            if (!PlayServModuleManifest.TryGet(moduleId, out _))");
            sb.AppendLine("                throw new InvalidOperationException($\"Generated module registry references unknown module id: {moduleId}\");");
            sb.AppendLine();
            sb.AppendLine("            host.Register(factory());");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static void AppendIndentedLines(StringBuilder sb, IReadOnlyList<string> lines, string indentation)
        {
            for (var i = 0; i < lines.Count; i++)
            {
                if (string.IsNullOrEmpty(lines[i]))
                    sb.AppendLine();
                else
                    sb.Append(indentation).AppendLine(lines[i]);
            }
        }

        private static void AddUnique(ICollection<string> values, string value)
        {
            if (!values.Contains(value))
                values.Add(value);
        }

        private static string QuoteCSharpString(string value)
        {
            return "\"" + (value ?? string.Empty)
                .Replace("\\", "\\\\")
                .Replace("\"", "\\\"") + "\"";
        }

        private static bool WriteIfChanged(string relativePath, string contents, bool importAsset)
        {
            if (!TryGetPackageRoot(out var packageRoot))
                return false;

            var path = packageRoot.ToAbsolutePath(relativePath);
            return WriteAbsolutePathIfChanged(path, contents, importAsset);
        }

        private static bool WriteAssetPathIfChanged(string assetPath, string contents, bool importAsset)
        {
            var path = PlayServPackagePathResolver.ToAbsoluteAssetPath(assetPath);
            return WriteAbsolutePathIfChanged(path, contents, importAsset);
        }

        private static bool WriteAbsolutePathIfChanged(string path, string contents, bool importAsset)
        {
            var directory = Path.GetDirectoryName(path);
            if (!string.IsNullOrEmpty(directory))
                Directory.CreateDirectory(directory);

            contents = NormalizeLineEndings(contents);
            if (File.Exists(path) && NormalizeLineEndings(File.ReadAllText(path)) == contents)
                return false;

            File.WriteAllText(path, contents);
            if (importAsset)
                AssetDatabase.ImportAsset(ToAssetPath(path), ImportAssetOptions.ForceUpdate);
            return true;
        }

        private static string NormalizeLineEndings(string value)
        {
            return (value ?? string.Empty).Replace("\r\n", "\n").Replace("\r", "\n");
        }

        private static bool TryGetPackageRoot(out PlayServPackageRoot packageRoot)
        {
            if (_packageRoot != null)
            {
                if (_packageRoot.Exists)
                {
                    packageRoot = _packageRoot;
                    return true;
                }

                _packageRoot = null;
            }

            if (!PlayServPackagePathResolver.TryResolveRootForScript(
                nameof(PlayServGeneratedCompatibilityLayer),
                ThisScriptSuffix,
                out packageRoot))
            {
                return false;
            }

            _packageRoot = packageRoot;
            return true;
        }

        private static string ToAssetPath(string absolutePath)
        {
            return TryGetPackageRoot(out var packageRoot)
                ? packageRoot.ToAssetPath(absolutePath)
                : PlayServPackagePathResolver.ToProjectAssetPath(absolutePath);
        }
    }

    [InitializeOnLoad]
    internal static class PlayServModuleGraphSynchronizer
    {
        private static bool _syncQueued;

        static PlayServModuleGraphSynchronizer()
        {
            QueueSync();
        }

        public static void QueueSync()
        {
            if (_syncQueued)
                return;

            _syncQueued = true;
            EditorApplication.delayCall += SyncNow;
        }

        public static void SyncNow()
        {
            SyncNow(refreshAssetDatabase: true);
        }

        internal static void SyncNow(bool refreshAssetDatabase)
        {
            _syncQueued = false;

            PlayServEditorModuleAvailability.SyncUnavailableModuleDefines();
            var state = LoadActiveState();

            var changed = false;
            changed |= PlayServCoreAssemblyReferenceSync.Sync(state, importAssets: refreshAssetDatabase);
            changed |= PlayServGeneratedCompatibilityLayer.SyncGeneratedFiles(state, importAssets: refreshAssetDatabase);

            if (changed && refreshAssetDatabase && !EditorApplication.isCompiling)
                AssetDatabase.Refresh();
        }

        internal static PlayServRuntimeModuleState LoadActiveState()
        {
            var state = PlayServRuntimeModuleDefines.LoadUserPreferenceState();
            PlayServEditorModuleAvailability.NormalizeAvailableRuntimeState(state);
            PlayServRuntimeModuleDefines.NormalizeDependencies(state);
            return state;
        }
    }

    internal sealed class PlayServGeneratedCompatibilityAssetPostprocessor : AssetPostprocessor
    {
        private static void OnPostprocessAllAssets(
            string[] importedAssets,
            string[] deletedAssets,
            string[] movedAssets,
            string[] movedFromAssetPaths)
        {
            if (TouchesModuleLayout(importedAssets) ||
                TouchesModuleLayout(deletedAssets) ||
                TouchesModuleLayout(movedAssets) ||
                TouchesModuleLayout(movedFromAssetPaths))
            {
                PlayServModuleGraphSynchronizer.SyncNow();
            }
        }

        private static bool TouchesModuleLayout(string[] paths)
        {
            if (paths == null)
                return false;

            for (var i = 0; i < paths.Length; i++)
            {
                var path = (paths[i] ?? string.Empty).Replace('\\', '/');
                if (!PlayServPackagePathResolver.TryGetPackageRelativeAssetPath(path, out var relativePath))
                    continue;

                if (relativePath.StartsWith("Runtime/Modules/", StringComparison.OrdinalIgnoreCase) ||
                    relativePath.StartsWith("Runtime/Proxy/Modules/", StringComparison.OrdinalIgnoreCase) ||
                    string.Equals(relativePath, "Runtime/Playserv.Runtime.asmdef", StringComparison.OrdinalIgnoreCase) ||
                    relativePath.StartsWith("Editor/Events/", StringComparison.OrdinalIgnoreCase) ||
                    relativePath.StartsWith("Editor/ModelGenerator/", StringComparison.OrdinalIgnoreCase) ||
                    relativePath.StartsWith("Editor/CodeGenerator/", StringComparison.OrdinalIgnoreCase))
                {
                    return true;
                }
            }

            return false;
        }
    }
