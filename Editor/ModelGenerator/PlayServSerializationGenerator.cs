using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using UnityEditor;
using UnityEditor.Build;
using UnityEngine;

namespace Playserv.Editor
{
    /// <summary>Generates opt-in runtime metadata before the consuming project's next compilation.</summary>
    public static class PlayServSerializationGenerator
    {
        internal const string Root = "Assets/PlayServGenerated/Serialization/";
        internal const string FirstPassRoot = "Assets/Plugins/PlayServGenerated/Serialization/";
        private const string Marker = "Playserv.Serialization.PlayServGeneratedSerializationAttribute";
        private const string Header = "// Generated by PlayServ serialization. Regenerate using Tools > PlayServ > Generate Serialization Metadata.\n";

        [MenuItem("Tools/PlayServ/Generate Serialization Metadata")]
        public static void Generate() => GenerateForBuild(ActiveOptions());

        /// <summary>Use the same options as the subsequent build, including extra scripting defines.</summary>
        public static void GenerateForBuild(BuildPlayerOptions options)
        {
            var inputs = PlayServContractBuildInputs.Collect(options);
            var result = BuildVariants(inputs, EditorInputs(inputs));
            foreach (var diagnostic in result.Diagnostics) Debug.LogWarning(diagnostic);
            Write(result, Directory.GetCurrentDirectory());
            AssetDatabase.Refresh();
            Debug.Log("PlayServ serialization: generated " + result.TypeCount + " contracts. Wait for compilation before building.");
        }

        internal static BuildPlayerOptions ActiveOptions() => new BuildPlayerOptions
        {
            target = EditorUserBuildSettings.activeBuildTarget,
            subtarget = (int)EditorUserBuildSettings.standaloneBuildSubtarget,
            options = EditorUserBuildSettings.development ? BuildOptions.Development : BuildOptions.None
        };

        internal sealed class Result
        {
            public readonly Dictionary<string, string> Files = new Dictionary<string, string>(StringComparer.Ordinal);
            public readonly List<string> Diagnostics = new List<string>();
            public int TypeCount;
        }

        internal static PlayServContractBuildInputs EditorInputs(PlayServContractBuildInputs player)
        {
            var names = new HashSet<string>(player.assemblies.Select(a => a.name), StringComparer.Ordinal);
            return new PlayServContractBuildInputs
            {
                assemblies = UnityEditor.Compilation.CompilationPipeline.GetAssemblies(UnityEditor.Compilation.AssembliesType.Editor)
                    .Where(a => names.Contains(a.name)).Select(a => new PlayServContractBuildAssembly
                    {
                        name = a.name, sources = a.sourceFiles.Select(Path.GetFullPath).ToArray(), defines = a.defines,
                        assemblyReferences = a.assemblyReferences.Select(r => r.name).ToArray(),
                        references = a.compiledAssemblyReferences.Concat(a.assemblyReferences.Select(r => Path.GetFullPath(r.outputPath)))
                            .Distinct(StringComparer.Ordinal).ToArray()
                    }).ToArray()
            };
        }

        internal static Result BuildVariants(PlayServContractBuildInputs player, PlayServContractBuildInputs editor)
        {
            var result = Build(player);
            var edit = Build(editor);
            foreach (var path in result.Files.Keys.Union(edit.Files.Keys).OrderBy(p => p, StringComparer.Ordinal).ToArray())
            {
                result.Files.TryGetValue(path, out var playerText);
                edit.Files.TryGetValue(path, out var editorText);
                if (path.EndsWith("link.xml", StringComparison.Ordinal) && playerText == null) continue;
                result.Files[path] = path.EndsWith(".cs", StringComparison.Ordinal)
                    ? "#if UNITY_EDITOR\n" + editorText + "#else\n" + playerText + "#endif\n"
                    : playerText ?? editorText;
            }
            foreach (var diagnostic in edit.Diagnostics)
                if (!result.Diagnostics.Contains(diagnostic)) result.Diagnostics.Add(diagnostic + " (Editor)");
            return result;
        }

        internal static Result Build(PlayServContractBuildInputs inputs)
        {
            // Generated files must not feed discovery, especially the assembly-level linker attribute.
            inputs = new PlayServContractBuildInputs { assemblies = inputs.assemblies.Select(a => new PlayServContractBuildAssembly
            {
                name = a.name, defines = a.defines, references = a.references, assemblyReferences = a.assemblyReferences,
                sources = a.sources.Where(path => !IsOutput(path)).ToArray()
            }).ToArray() };
            var result = new Result();
            if (!MayContainOptIn(inputs)) return result;
            var preserved = new Dictionary<string, SortedSet<string>>(StringComparer.Ordinal);
            foreach (var compilation in inputs.CreateCompilations().Select(c => c.WithOptions(c.Options.WithAllowUnsafe(true)))
                         .OrderBy(c => c.AssemblyName, StringComparer.Ordinal))
            {
                var selected = Types(compilation.Assembly.GlobalNamespace).Where(t => Has(t, Marker))
                    .OrderBy(t => t.ToDisplayString(), StringComparer.Ordinal).ToArray();
                if (selected.Length == 0) continue;
                Preserve(selected, preserved);
                var errors = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();
                if (errors.Length > 0)
                    throw new BuildFailedException("PlayServ serialization requires compilable player contracts:\n" + string.Join("\n", errors.Select(d => d.ToString())));
                var registrations = new List<string>();
                foreach (var type in selected)
                {
                    if (!TryDescribe(type, out var members, out var reason))
                    {
                        result.Diagnostics.Add("PlayServ serialization: " + type.ToDisplayString() + " uses reflection fallback: " + reason);
                        continue;
                    }
                    registrations.Add(Registration(type, members));
                    result.TypeCount++;
                }
                if (registrations.Count == 0) continue;
                var directory = (compilation.AssemblyName == "Assembly-CSharp-firstpass" ? FirstPassRoot : Root) + SafeName(compilation.AssemblyName) + "/";
                if (compilation.AssemblyName != "Assembly-CSharp" && compilation.AssemblyName != "Assembly-CSharp-firstpass")
                    result.Files.Add(directory + "PlayServSerialization.asmref", "{\n  \"reference\": " + Quote(compilation.AssemblyName) + "\n}\n");
                var code = new StringBuilder(Header);
                if (!Has(compilation.Assembly, "UnityEngine.Scripting.AlwaysLinkAssemblyAttribute"))
                    code.AppendLine("[assembly: global::UnityEngine.Scripting.AlwaysLinkAssembly]");
                code.AppendLine("namespace Playserv.GeneratedSerialization");
                code.AppendLine("{");
                code.AppendLine("    [global::UnityEngine.Scripting.Preserve]");
                code.AppendLine("    internal static class Registration");
                code.AppendLine("    {");
                code.AppendLine("#if UNITY_EDITOR");
                code.AppendLine("        [global::UnityEditor.InitializeOnLoadMethod]");
                code.AppendLine("#endif");
                code.AppendLine("        [global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.SubsystemRegistration)]");
                code.AppendLine("        [global::UnityEngine.Scripting.Preserve]");
                code.AppendLine("        internal static void Register()");
                code.AppendLine("        {");
                foreach (var registration in registrations) code.Append(registration);
                code.AppendLine("        }");
                code.AppendLine("    }");
                code.AppendLine("}");
                var generated = code.ToString().Replace("\r\n", "\n");
                var parseOptions = compilation.SyntaxTrees.FirstOrDefault()?.Options as CSharpParseOptions ?? new CSharpParseOptions();
                var generatedErrors = compilation.AddSyntaxTrees(CSharpSyntaxTree.ParseText(generated, parseOptions))
                    .GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();
                if (generatedErrors.Length > 0)
                    throw new BuildFailedException("PlayServ generated serialization did not compile:\n" + string.Join("\n", generatedErrors.Select(d => d.ToString())));
                result.Files.Add(directory + "PlayServSerialization.g.cs", generated);
            }
            if (preserved.Count > 0)
            {
                var xml = new XElement("linker", preserved.OrderBy(p => p.Key, StringComparer.Ordinal).Select(assembly =>
                    new XElement("assembly", new XAttribute("fullname", assembly.Key),
                        assembly.Value.Select(type => new XElement("type", new XAttribute("fullname", type), new XAttribute("preserve", "all"))))));
                result.Files.Add(Root + "link.xml", xml.ToString().Replace("\r\n", "\n") + "\n");
            }
            return result;
        }

        private static bool MayContainOptIn(PlayServContractBuildInputs inputs)
        {
            bool IsMarker(SyntaxToken token) => token.ValueText == "PlayServGeneratedSerialization" ||
                                                token.ValueText == "PlayServGeneratedSerializationAttribute";
            foreach (var assembly in inputs.assemblies)
            {
                var options = new CSharpParseOptions(LanguageVersion.Latest, preprocessorSymbols: assembly.defines);
                foreach (var path in assembly.sources)
                {
                    var source = File.ReadAllText(path);
                    if (source.IndexOf("PlayServGeneratedSerialization", StringComparison.Ordinal) < 0 &&
                        source.IndexOf("\\u", StringComparison.Ordinal) < 0 && source.IndexOf("\\U", StringComparison.Ordinal) < 0 &&
                        !source.Any(character => character > 127)) continue;
                    var syntax = CSharpSyntaxTree.ParseText(source, options, path).GetRoot();
                    if (syntax.DescendantNodes().OfType<AttributeSyntax>().Any(a => a.Name.DescendantTokens().Any(IsMarker)) ||
                        syntax.DescendantNodes().OfType<UsingDirectiveSyntax>().Any(u =>
                            u.Alias != null && u.Name != null && u.Name.DescendantTokens().Any(IsMarker))) return true;
                }
            }
            return false;
        }

        private static void Preserve(IEnumerable<INamedTypeSymbol> roots, Dictionary<string, SortedSet<string>> result)
        {
            var visited = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
            var definitions = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
            void Visit(ITypeSymbol symbol)
            {
                if (symbol == null || !visited.Add(symbol)) return;
                if (symbol is IArrayTypeSymbol array) { Visit(array.ElementType); return; }
                if (!(symbol is INamedTypeSymbol type)) return;
                foreach (var argument in type.TypeArguments) if (argument.TypeKind != TypeKind.TypeParameter) Visit(argument);
                var ns = type.ContainingNamespace.ToDisplayString();
                if (new[] { "System", "UnityEngine", "UnityEditor", "Newtonsoft" }.Any(prefix => ns == prefix || ns.StartsWith(prefix + ".", StringComparison.Ordinal))) return;
                var assembly = type.ContainingAssembly.Name;
                if (!result.TryGetValue(assembly, out var names)) result[assembly] = names = new SortedSet<string>(StringComparer.Ordinal);
                names.Add(LinkName(type.OriginalDefinition));
                if (!definitions.Add(type.OriginalDefinition)) return;
                if (assembly.StartsWith("Playserv.Runtime", StringComparison.Ordinal)) return;
                Visit(type.BaseType);
                foreach (var member in type.GetMembers().Where(m => !m.IsStatic))
                {
                    if (member is IFieldSymbol field) Visit(field.Type);
                    else if (member is IPropertySymbol property) Visit(property.Type);
                }
            }
            foreach (var root in roots) Visit(root);
        }

        private static string LinkName(INamedTypeSymbol type) => type.ContainingType != null
            ? LinkName(type.ContainingType) + "/" + type.MetadataName
            : (type.ContainingNamespace.IsGlobalNamespace ? "" : type.ContainingNamespace.ToDisplayString() + ".") + type.MetadataName;

        private sealed class Member
        {
            public string Name;
            public string WireName;
            public ITypeSymbol Type;
            public bool Ignored;
        }

        private static bool TryDescribe(INamedTypeSymbol type, out List<Member> members, out string reason)
        {
            members = new List<Member>();
            reason = null;
            if (type.TypeKind != TypeKind.Class || type.IsAbstract || type.IsStatic || type.IsRecord ||
                type.BaseType?.SpecialType != SpecialType.System_Object)
                return Refuse("only mutable, non-derived DTO classes are generated", out reason);
            for (var current = type; current != null; current = current.ContainingType)
                if (current.Arity != 0 || (current.DeclaredAccessibility != Accessibility.Public && current.DeclaredAccessibility != Accessibility.Internal))
                    return Refuse("generic or inaccessible DTO/containing type", out reason);
            if (!type.InstanceConstructors.Any(c => c.Parameters.Length == 0 && c.DeclaredAccessibility == Accessibility.Public))
                return Refuse("a public parameterless constructor is required", out reason);
            if (type.AllInterfaces.Any(i => i.ToDisplayString() == "System.Runtime.Serialization.ISerializable" ||
                    i.ToDisplayString() == "System.Collections.IEnumerable" || i.ToDisplayString() == "System.Dynamic.IDynamicMetaObjectProvider") ||
                Has(type, "System.ComponentModel.TypeConverterAttribute") || SpecialAttributes(type))
                return Refuse("custom object serialization attributes or ISerializable", out reason);
            var all = type.GetMembers();
            if (all.Any(m => m.Name.StartsWith("ShouldSerialize", StringComparison.Ordinal) ||
                             m.Name.EndsWith("Specified", StringComparison.Ordinal) ||
                             m is IMethodSymbol && SpecialAttributes(m)))
                return Refuse("conditional members or serialization callbacks", out reason);
            foreach (var symbol in all)
            {
                if (!(symbol is IFieldSymbol) && !(symbol is IPropertySymbol)) continue;
                if (symbol.IsImplicitlyDeclared) continue;
                if (Has(symbol, "System.Runtime.CompilerServices.CompilerGeneratedAttribute"))
                    return Refuse("compiler-generated member " + symbol.Name, out reason);
                if (symbol.IsStatic || symbol.DeclaredAccessibility != Accessibility.Public)
                {
                    if (SpecialAttributes(symbol, "Newtonsoft.Json.JsonIgnoreAttribute", "System.Runtime.Serialization.IgnoreDataMemberAttribute"))
                        return Refuse("attributed static or non-public member " + symbol.Name, out reason);
                    continue;
                }
                var ignored = Has(symbol, "Newtonsoft.Json.JsonIgnoreAttribute") || Has(symbol, "Playserv.Schema.PlayServIgnoreAttribute") ||
                              Has(symbol, "System.NonSerializedAttribute") || Has(symbol, "System.Runtime.Serialization.IgnoreDataMemberAttribute");
                var json = Attribute(symbol, "Newtonsoft.Json.JsonPropertyAttribute");
                if (SpecialAttributes(symbol, "Newtonsoft.Json.JsonPropertyAttribute", "Newtonsoft.Json.JsonIgnoreAttribute", "System.Runtime.Serialization.IgnoreDataMemberAttribute") ||
                    Has(symbol, "System.ComponentModel.DefaultValueAttribute") ||
                    json != null && json.NamedArguments.Any(a => a.Key != "PropertyName"))
                    return Refuse("unsupported JSON options on " + symbol.Name, out reason);
                ITypeSymbol valueType;
                if (symbol is IFieldSymbol field)
                {
                    if (!ignored && (field.IsReadOnly || field.IsFixedSizeBuffer)) return Refuse("read-only/fixed field " + symbol.Name, out reason);
                    valueType = field.Type;
                }
                else
                {
                    var property = (IPropertySymbol)symbol;
                    if (property.IsIndexer || property.ReturnsByRef || property.ReturnsByRefReadonly)
                        return Refuse("indexer or ref-return property " + symbol.Name, out reason);
                    if (!ignored && (property.GetMethod?.DeclaredAccessibility != Accessibility.Public ||
                        property.SetMethod?.DeclaredAccessibility != Accessibility.Public || property.SetMethod.IsInitOnly))
                        return Refuse("read-only or inaccessible property " + symbol.Name, out reason);
                    valueType = property.Type;
                }
                if (valueType.TypeKind == TypeKind.Pointer || valueType.TypeKind == TypeKind.FunctionPointer || valueType.IsRefLikeType)
                    return Refuse("unsupported member type " + symbol.Name, out reason);
                var name = Name(Attribute(symbol, "Playserv.Serialization.PlayServJsonNameAttribute"));
                if (string.IsNullOrWhiteSpace(name)) name = Name(Attribute(symbol, "Playserv.Schema.PlayServFieldAttribute"));
                if (string.IsNullOrWhiteSpace(name)) name = json?.NamedArguments.FirstOrDefault(a => a.Key == "PropertyName").Value.Value as string ?? Name(json) ?? symbol.Name;
                if (members.Any(m => string.Equals(m.WireName, name, StringComparison.OrdinalIgnoreCase)))
                    return Refuse("ambiguous case-insensitive JSON name " + name, out reason);
                members.Add(new Member { Name = symbol.Name, WireName = name, Type = valueType, Ignored = ignored });
            }
            members = members.OrderBy(m => m.WireName, StringComparer.Ordinal).ToList();
            return true;
        }

        private static string Registration(INamedTypeSymbol type, List<Member> members)
        {
            var name = TypeName(type);
            var text = new StringBuilder("            global::Playserv.Serialization.PlayServGeneratedContracts.Register<" + name + ">(() => new " + name + "()");
            foreach (var member in members)
            {
                text.Append(",\n                global::Playserv.Serialization.PlayServGeneratedProperty.");
                if (member.Ignored) text.Append("Ignore<" + name + ">(" + Quote(member.WireName) + ", " + Quote(member.Name) + ")");
                else text.Append("Create<" + name + ", " + TypeName(member.Type) + ">(" + Quote(member.WireName) + ", " + Quote(member.Name) +
                    ", x => x.@" + member.Name + ", (x, value) => x.@" + member.Name + " = value)");
            }
            return text.Append(");\n").ToString();
        }

        private static string TypeName(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        private static string Quote(string value) => SymbolDisplay.FormatLiteral(value, true);
        private static string Name(AttributeData attribute) => attribute?.ConstructorArguments.FirstOrDefault().Value as string;
        private static AttributeData Attribute(ISymbol symbol, string name) => symbol.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == name);
        private static bool Has(ISymbol symbol, string name) => Attribute(symbol, name) != null;
        private static bool Refuse(string message, out string reason) { reason = message; return false; }
        private static bool SpecialAttributes(ISymbol symbol, params string[] allowed) => symbol.GetAttributes().Any(a =>
        {
            var name = a.AttributeClass?.ToDisplayString() ?? "";
            return (name.StartsWith("Newtonsoft.Json.", StringComparison.Ordinal) || name.StartsWith("System.Runtime.Serialization.", StringComparison.Ordinal)) && !allowed.Contains(name);
        });
        private static IEnumerable<INamedTypeSymbol> Types(INamespaceOrTypeSymbol parent)
        {
            foreach (var type in parent.GetTypeMembers())
            {
                yield return type;
                foreach (var nested in Types(type)) yield return nested;
            }
            if (parent is INamespaceSymbol ns)
                foreach (var child in ns.GetNamespaceMembers())
                    foreach (var type in Types(child)) yield return type;
        }

        private static string SafeName(string name) => string.Concat(name.Select(c => char.IsLetterOrDigit(c) || c == '.' || c == '-' || c == '_' ? c : '_'));
        internal static bool IsOutput(string path)
        {
            path = path.Replace('\\', '/');
            return path.StartsWith(Root, StringComparison.OrdinalIgnoreCase) || path.Contains("/" + Root) ||
                   path.StartsWith(FirstPassRoot, StringComparison.OrdinalIgnoreCase) || path.Contains("/" + FirstPassRoot);
        }

        internal static void Write(Result result, string projectRoot)
        {
            foreach (var previous in OutputFiles(projectRoot).Except(result.Files.Keys, StringComparer.Ordinal))
            {
                var path = Path.Combine(projectRoot, previous);
                File.Delete(path);
                if (File.Exists(path + ".meta")) File.Delete(path + ".meta");
            }
            foreach (var file in result.Files)
            {
                var path = Path.Combine(projectRoot, file.Key);
                if (File.Exists(path) && NormalizeLines(File.ReadAllText(path)) == NormalizeLines(file.Value)) continue;
                Directory.CreateDirectory(Path.GetDirectoryName(path));
                File.WriteAllText(path, file.Value, new UTF8Encoding(false));
            }
        }

        internal static IEnumerable<string> OutputFiles(string projectRoot)
        {
            if (File.Exists(Path.Combine(projectRoot, Root + "link.xml"))) yield return Root + "link.xml";
            foreach (var root in new[] { Root, FirstPassRoot })
            {
                var path = Path.Combine(projectRoot, root);
                if (!Directory.Exists(path)) continue;
                foreach (var file in Directory.GetFiles(path, "PlayServSerialization.*", SearchOption.AllDirectories))
                    if (file.EndsWith(".g.cs", StringComparison.Ordinal) || file.EndsWith(".asmref", StringComparison.Ordinal))
                        yield return file.Substring(projectRoot.TrimEnd('/', '\\').Length + 1).Replace('\\', '/');
            }
        }

        internal static void Validate(PlayServContractBuildInputs inputs, string projectRoot)
        {
            var expected = Build(inputs);
            ValidateOutput(expected, projectRoot);
        }

        internal static void ValidateOutput(Result expected, string projectRoot)
        {
            var actual = OutputFiles(projectRoot).ToArray();
            if (actual.Except(expected.Files.Keys).Any() || expected.Files.Any(file =>
                    !File.Exists(Path.Combine(projectRoot, file.Key)) || NormalizeLines(File.ReadAllText(Path.Combine(projectRoot, file.Key))) != NormalizeLines(file.Value)))
                throw new BuildFailedException("PlayServ serialization metadata is missing or stale. Run Tools > PlayServ > Generate Serialization Metadata for this target/defines, wait for compilation, then build again.");
        }

        private static string NormalizeLines(string source) => source.Replace("\r\n", "\n");
    }
}
