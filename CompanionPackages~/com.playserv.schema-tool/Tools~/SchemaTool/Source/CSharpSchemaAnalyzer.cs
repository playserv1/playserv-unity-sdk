using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace PlayServ.Schema.Tool;

internal static class CSharpSchemaAnalyzer
{
    public static AnalysisSnapshot Analyze(
        string projectRoot,
        SchemaToolConfiguration configuration,
        IReadOnlyList<ContractSource>? buildSources = null)
    {
        var files = buildSources == null
            ? ProjectConfiguration.EnumerateSourceFiles(projectRoot, configuration)
            : buildSources.Select(source => source.Tree.FilePath).Distinct(StringComparer.Ordinal).OrderBy(file => file, StringComparer.Ordinal).ToArray();
        var contracts = new List<SchemaContract>();
        var diagnostics = new List<SchemaDiagnostic>();

        var sources = buildSources ?? files.Select(file => new ContractSource(file)).ToArray();
        foreach (var source in sources)
        {
            AnalyzeFile(projectRoot, configuration, source, sources, contracts, diagnostics);
        }

        foreach (var duplicate in contracts
                     .GroupBy(contract => contract.Id, StringComparer.Ordinal)
                     .Where(group => group.Count() > 1))
        {
            foreach (var contract in duplicate)
            {
                diagnostics.Add(new SchemaDiagnostic
                {
                    Severity = "error",
                    Code = "PSSCHEMA001",
                    Message = $"Duplicate schema id '{duplicate.Key}'.",
                    Path = contract.SourcePath,
                    Line = contract.SourceLine,
                    Column = 1,
                    Type = contract.FullName
                });
            }
        }

        if (buildSources != null)
            BuildContractValidation.ValidateReferences(contracts, diagnostics);

        foreach (var remoteSource in configuration.Sources.Where(source =>
                     string.Equals(source.Kind, "remote", StringComparison.OrdinalIgnoreCase)))
        {
            diagnostics.Add(new SchemaDiagnostic
            {
                Severity = "info",
                Code = "PSSCHEMA100",
                Message =
                    $"Remote source '{remoteSource.Id}' is configured. Service synchronization " +
                    "will activate when the Schema Service protocol is configured."
            });
        }

        return new AnalysisSnapshot
        {
            SourceFiles = files
                .Select(file => NormalizePath(Path.GetRelativePath(projectRoot, file)))
                .ToArray(),
            Contracts = contracts
                .OrderBy(contract => contract.Id, StringComparer.Ordinal)
                .ToArray(),
            Diagnostics = diagnostics
                .OrderBy(diagnostic => SeverityOrder(diagnostic.Severity))
                .ThenBy(diagnostic => diagnostic.Path, StringComparer.Ordinal)
                .ThenBy(diagnostic => diagnostic.Line)
                .ThenBy(diagnostic => diagnostic.Column)
                .ThenBy(diagnostic => diagnostic.Code, StringComparer.Ordinal)
                .ThenBy(diagnostic => diagnostic.Type, StringComparer.Ordinal)
                .ThenBy(diagnostic => diagnostic.Member, StringComparer.Ordinal)
                .ThenBy(diagnostic => diagnostic.Message, StringComparer.Ordinal)
                .ToArray()
        };
    }

    private static void AnalyzeFile(
        string projectRoot,
        SchemaToolConfiguration configuration,
        ContractSource source,
        IReadOnlyList<ContractSource> sources,
        ICollection<SchemaContract> contracts,
        ICollection<SchemaDiagnostic> diagnostics)
    {
        var file = source.Tree.FilePath;
        var text = source.Tree.GetText().ToString();
        if (source.Model == null && text.AsSpan(0, Math.Min(text.Length, 256))
            .IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0)
        {
            return;
        }

        var tree = source.Tree;
        foreach (var diagnostic in tree.GetDiagnostics().Where(diagnostic =>
                     diagnostic.Severity == DiagnosticSeverity.Error))
        {
            var line = diagnostic.Location.GetLineSpan().StartLinePosition.Line + 1;
            diagnostics.Add(new SchemaDiagnostic
            {
                Severity = "error",
                Code = "PSSCHEMA002",
                Message = diagnostic.GetMessage(),
                Path = NormalizePath(Path.GetRelativePath(projectRoot, file)),
                Line = line,
                Column = diagnostic.Location.GetLineSpan().StartLinePosition.Character + 1
            });
        }

        var root = tree.GetCompilationUnitRoot();
        var relativePath = NormalizePath(Path.GetRelativePath(projectRoot, file));
        var sourceId = ProjectConfiguration.ResolveSourceId(projectRoot, configuration, file);
        var sourceAuthority = ProjectConfiguration.ResolveAuthority(configuration, sourceId);

        foreach (var declaration in root.DescendantNodes().OfType<BaseTypeDeclarationSyntax>())
        {
            var schemaAttribute = FindAttribute(declaration.AttributeLists, "PlayServSchema", source.Model);
            if (schemaAttribute == null)
                continue;

            var namespaceName = ResolveNamespace(declaration);
            var containingTypes = declaration.Ancestors()
                .OfType<BaseTypeDeclarationSyntax>()
                .Reverse()
                .Select(type => type.Identifier.ValueText);
            var qualifiedNameParts = new List<string>();
            if (!string.IsNullOrWhiteSpace(namespaceName))
                qualifiedNameParts.Add(namespaceName);
            qualifiedNameParts.AddRange(containingTypes);
            qualifiedNameParts.Add(declaration.Identifier.ValueText);
            var fullName = string.Join(".", qualifiedNameParts);
            var id = ReadPositionalString(schemaAttribute, 0);
            if (string.IsNullOrWhiteSpace(id))
                id = fullName;

            var authority = ReadNamedValue(schemaAttribute, "Authority");
            if (string.IsNullOrWhiteSpace(authority))
                authority = sourceAuthority;
            authority = NormalizeEnumValue(authority).ToLowerInvariant();

            var version = ReadNamedString(schemaAttribute, "Version");
            var description = ReadNamedString(schemaAttribute, "Description");
            var declaredKind = NormalizeEnumValue(ReadNamedValue(schemaAttribute, "Kind"));
            var singleton = ReadNamedBoolean(schemaAttribute, "Singleton");
            var displayField = ReadNamedString(schemaAttribute, "DisplayField");
            var ownedBy = NormalizeEnumValue(ReadNamedValue(schemaAttribute, "OwnedBy"));
            var readPolicy = NormalizeEnumValue(ReadNamedValue(schemaAttribute, "Read"));
            var onPlayerDelete = NormalizeEnumValue(ReadNamedValue(schemaAttribute, "OnPlayerDelete"));
            var allowRawFields = ReadNamedBoolean(schemaAttribute, "AllowRawFields");
            var clientRead = NormalizeEnumValue(ReadNamedValue(schemaAttribute, "ClientRead"));
            var clientWrite = NormalizeEnumValue(ReadNamedValue(schemaAttribute, "ClientWrite"));
            var serverRead = NormalizeEnumValue(ReadNamedValue(schemaAttribute, "ServerRead"));
            var serverWrite = NormalizeEnumValue(ReadNamedValue(schemaAttribute, "ServerWrite"));
            var backendRead = NormalizeEnumValue(ReadNamedValue(schemaAttribute, "BackendRead"));
            var backendWrite = NormalizeEnumValue(ReadNamedValue(schemaAttribute, "BackendWrite"));
            var line = declaration.GetLocation().GetLineSpan().StartLinePosition.Line + 1;
            var formerNames = ReadFormerNames(declaration.AttributeLists);

            if (declaration is EnumDeclarationSyntax enumDeclaration)
            {
                contracts.Add(new SchemaContract
                {
                    Id = id.Trim(),
                    Name = declaration.Identifier.ValueText,
                    FullName = fullName,
                    Kind = "enum",
                    Authority = authority,
                    Version = version,
                    Description = description,
                    SourceId = sourceId,
                    SourcePath = relativePath,
                    SourceLine = line,
                    FormerNames = formerNames,
                    EnumValues = enumDeclaration.Members
                        .Select(member => member.Identifier.ValueText)
                        .ToArray()
                });
                continue;
            }

            var parts = source.Model?.GetDeclaredSymbol(declaration)?.DeclaringSyntaxReferences
                .Select(reference => reference.GetSyntax()).OfType<BaseTypeDeclarationSyntax>().ToArray()
                ?? new[] { declaration };
            var members = parts.SelectMany(part => ReadMembers(part,
                    NormalizePath(Path.GetRelativePath(projectRoot, part.SyntaxTree.FilePath)),
                    sources.FirstOrDefault(candidate => candidate.Tree == part.SyntaxTree)?.Model))
                .OrderBy(member => member.Name, StringComparer.Ordinal).ThenBy(member => member.SourcePath, StringComparer.Ordinal)
                .ThenBy(member => member.SourceLine).ToArray();
            foreach (var duplicate in members.GroupBy(member => member.Name, StringComparer.Ordinal).Where(group => group.Count() > 1))
            foreach (var member in duplicate)
                diagnostics.Add(new SchemaDiagnostic
                {
                    Severity = "error", Code = "PSSCHEMA003",
                    Message = $"Type '{fullName}' contains duplicate schema field '{duplicate.Key}' ({member.SourceName}).",
                    Path = member.SourcePath, Line = member.SourceLine, Column = member.SourceColumn,
                    Type = fullName, Member = member.SourceName
                });
            var kind = declaredKind switch
            {
                "Entity" => "object",
                "Part" => "struct",
                _ => declaration is StructDeclarationSyntax ? "struct" : "object"
            };
            contracts.Add(new SchemaContract
            {
                Id = id.Trim(),
                Name = declaration.Identifier.ValueText,
                FullName = fullName,
                Kind = kind,
                Authority = authority,
                Version = version,
                Description = description,
                Singleton = singleton,
                DisplayField = displayField,
                OwnedBy = ownedBy,
                ReadPolicy = readPolicy,
                OnPlayerDelete = onPlayerDelete,
                AllowRawFields = allowRawFields,
                ClientRead = clientRead,
                ClientWrite = clientWrite,
                ServerRead = serverRead,
                ServerWrite = serverWrite,
                BackendRead = backendRead,
                BackendWrite = backendWrite,
                SourceId = sourceId,
                SourcePath = relativePath,
                SourceLine = line,
                FormerNames = formerNames,
                Members = members
            });
        }
    }

    private static IReadOnlyList<SchemaMember> ReadMembers(
        BaseTypeDeclarationSyntax declaration,
        string path,
        SemanticModel? model)
    {
        var members = new List<SchemaMember>();
        if (declaration is RecordDeclarationSyntax record && record.ParameterList != null)
        {
            foreach (var parameter in record.ParameterList.Parameters)
            {
                if (parameter.Type == null ||
                    FindAttribute(parameter.AttributeLists, "PlayServIgnore", model) != null ||
                    record.Members.OfType<PropertyDeclarationSyntax>().Any(property => property.Identifier.ValueText == parameter.Identifier.ValueText) ||
                    (model?.GetDeclaredSymbol(record) as INamedTypeSymbol)?.GetMembers(parameter.Identifier.ValueText)
                        .OfType<IPropertySymbol>().Any(property => property.DeclaringSyntaxReferences.Any(reference => reference.GetSyntax() is PropertyDeclarationSyntax)) == true)
                {
                    continue;
                }

                members.Add(CreateMember(
                    parameter.Identifier.ValueText,
                    parameter.Type,
                    parameter.AttributeLists, parameter, path, model));
            }
        }

        if (declaration is not TypeDeclarationSyntax typeDeclaration)
            return members;

        foreach (var property in typeDeclaration.Members.OfType<PropertyDeclarationSyntax>())
        {
            if (!HasModifier(property.Modifiers, SyntaxKind.PublicKeyword) ||
                HasModifier(property.Modifiers, SyntaxKind.StaticKeyword) ||
                FindAttribute(property.AttributeLists, "PlayServIgnore", model) != null)
            {
                continue;
            }

            members.Add(CreateMember(
                property.Identifier.ValueText,
                property.Type,
                property.AttributeLists, property, path, model));
        }

        foreach (var field in typeDeclaration.Members.OfType<FieldDeclarationSyntax>())
        {
            if (!HasModifier(field.Modifiers, SyntaxKind.PublicKeyword) ||
                HasModifier(field.Modifiers, SyntaxKind.StaticKeyword) ||
                HasModifier(field.Modifiers, SyntaxKind.ConstKeyword) ||
                FindAttribute(field.AttributeLists, "PlayServIgnore", model) != null)
            {
                continue;
            }

            foreach (var variable in field.Declaration.Variables)
            {
                members.Add(CreateMember(
                    variable.Identifier.ValueText,
                    field.Declaration.Type,
                    field.AttributeLists, variable, path, model));
            }
        }

        return members
            .OrderBy(member => member.Name, StringComparer.Ordinal)
            .ToArray();
    }

    private static SchemaMember CreateMember(
        string sourceName,
        TypeSyntax type,
        SyntaxList<AttributeListSyntax> attributes,
        SyntaxNode location,
        string path,
        SemanticModel? model)
    {
        var fieldAttribute = FindAttribute(attributes, "PlayServField", model);
        var name = fieldAttribute == null
            ? sourceName
            : ReadPositionalString(fieldAttribute, 0);
        if (string.IsNullOrWhiteSpace(name))
            name = sourceName;

        var requiredMode = fieldAttribute == null
            ? string.Empty
            : NormalizeEnumValue(ReadNamedValue(fieldAttribute, "Required"));
        var required = requiredMode switch
        {
            "Required" => true,
            "Optional" => false,
            _ => type is not NullableTypeSyntax
        };

        return new SchemaMember
        {
            SourcePath = path,
            SourceLine = location.GetLocation().GetLineSpan().StartLinePosition.Line + 1,
            SourceColumn = location.GetLocation().GetLineSpan().StartLinePosition.Character + 1,
            Name = name.Trim(),
            SourceName = sourceName,
            TypeName = model?.GetTypeInfo(type).Type?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                ?? type.WithoutTrivia().ToString(),
            FieldType = fieldAttribute == null
                ? string.Empty
                : NormalizeEnumValue(ReadNamedValue(fieldAttribute, "Type")),
            Required = required,
            CodeKey = fieldAttribute == null ? string.Empty : ReadNamedString(fieldAttribute, "CodeKey"),
            Primary = fieldAttribute != null && ReadNamedBoolean(fieldAttribute, "Primary"),
            Unique = fieldAttribute != null && ReadNamedBoolean(fieldAttribute, "Unique"),
            Indexed = fieldAttribute != null && ReadNamedBoolean(fieldAttribute, "Indexed"),
            Default = fieldAttribute == null ? string.Empty : ReadNamedString(fieldAttribute, "Default"),
            Target = fieldAttribute == null ? string.Empty : ReadNamedString(fieldAttribute, "Target"),
            Cardinality = fieldAttribute == null
                ? string.Empty
                : NormalizeEnumValue(ReadNamedValue(fieldAttribute, "Cardinality")),
            Ordered = fieldAttribute != null && ReadNamedBoolean(fieldAttribute, "Ordered"),
            FormerNames = ReadFormerNames(attributes)
        };
    }

    private static AttributeSyntax? FindAttribute(
        SyntaxList<AttributeListSyntax> lists,
        string expectedName,
        SemanticModel? model = null)
    {
        foreach (var attribute in lists.SelectMany(list => list.Attributes))
        {
            var matches = model == null
                ? NormalizeAttributeName(attribute.Name.ToString()) == expectedName
                : model.GetTypeInfo(attribute).Type?.ToDisplayString() == "Playserv.Schema." + expectedName + "Attribute";
            if (!matches) continue;
            if (model == null || attribute.ArgumentList == null) return attribute;
            return attribute.WithArgumentList(attribute.ArgumentList.WithArguments(SyntaxFactory.SeparatedList(
                attribute.ArgumentList.Arguments.Select(argument =>
                {
                    var value = model.GetConstantValue(argument.Expression);
                    ExpressionSyntax expression = argument.Expression;
                    var convertedType = model.GetTypeInfo(expression).ConvertedType;
                    if (value.HasValue && convertedType?.TypeKind == TypeKind.Enum)
                    {
                        var enumValue = convertedType.GetMembers().OfType<IFieldSymbol>()
                            .FirstOrDefault(field => field.HasConstantValue && Equals(field.ConstantValue, value.Value));
                        if (enumValue != null) expression = SyntaxFactory.IdentifierName(enumValue.Name);
                    }
                    else if (value.HasValue && value.Value is string str)
                        expression = SyntaxFactory.LiteralExpression(SyntaxKind.StringLiteralExpression, SyntaxFactory.Literal(str));
                    else if (value.HasValue && value.Value is bool boolean)
                        expression = SyntaxFactory.LiteralExpression(boolean ? SyntaxKind.TrueLiteralExpression : SyntaxKind.FalseLiteralExpression);
                    return argument.WithNameColon(null).WithExpression(expression);
                }))));
        }
        return null;
    }

    private static IReadOnlyList<string> ReadFormerNames(
        SyntaxList<AttributeListSyntax> attributes)
    {
        return attributes
            .SelectMany(list => list.Attributes)
            .Where(attribute => string.Equals(
                NormalizeAttributeName(attribute.Name.ToString()),
                "PlayServFormerlyNamed",
                StringComparison.Ordinal))
            .Select(attribute => ReadPositionalString(attribute, 0))
            .Where(value => !string.IsNullOrWhiteSpace(value))
            .Select(value => value.Trim())
            .Distinct(StringComparer.Ordinal)
            .OrderBy(value => value, StringComparer.Ordinal)
            .ToArray();
    }

    private static string ReadPositionalString(AttributeSyntax attribute, int index)
    {
        var arguments = attribute.ArgumentList?.Arguments
            .Where(argument => argument.NameEquals == null && argument.NameColon == null)
            .ToArray();
        if (arguments == null || index < 0 || index >= arguments.Length)
            return string.Empty;

        return ReadStringExpression(arguments[index].Expression);
    }

    private static string ReadNamedString(AttributeSyntax attribute, string name)
    {
        var argument = attribute.ArgumentList?.Arguments.FirstOrDefault(candidate =>
            string.Equals(candidate.NameEquals?.Name.Identifier.ValueText, name, StringComparison.Ordinal));
        return argument == null ? string.Empty : ReadStringExpression(argument.Expression);
    }

    private static string ReadNamedValue(AttributeSyntax attribute, string name)
    {
        var argument = attribute.ArgumentList?.Arguments.FirstOrDefault(candidate =>
            string.Equals(candidate.NameEquals?.Name.Identifier.ValueText, name, StringComparison.Ordinal));
        return argument?.Expression.WithoutTrivia().ToString() ?? string.Empty;
    }

    private static bool ReadNamedBoolean(AttributeSyntax attribute, string name)
    {
        var value = ReadNamedValue(attribute, name);
        return string.Equals(value, "true", StringComparison.OrdinalIgnoreCase);
    }

    private static string ReadStringExpression(ExpressionSyntax expression)
    {
        return expression is LiteralExpressionSyntax literal &&
               literal.IsKind(SyntaxKind.StringLiteralExpression)
            ? literal.Token.ValueText
            : string.Empty;
    }

    private static string ResolveNamespace(SyntaxNode declaration)
    {
        return string.Join(
            ".",
            declaration.Ancestors()
                .OfType<BaseNamespaceDeclarationSyntax>()
                .Reverse()
                .Select(namespaceDeclaration => namespaceDeclaration.Name.ToString()));
    }

    private static string NormalizeAttributeName(string name)
    {
        var simpleName = name.Split('.').Last();
        return simpleName.EndsWith("Attribute", StringComparison.Ordinal)
            ? simpleName[..^"Attribute".Length]
            : simpleName;
    }

    private static string NormalizeEnumValue(string value)
    {
        return (value ?? string.Empty).Split('.').Last().Trim();
    }

    private static bool HasModifier(
        SyntaxTokenList modifiers,
        SyntaxKind kind)
    {
        return modifiers.Any(token => token.IsKind(kind));
    }

    private static int SeverityOrder(string severity)
    {
        return severity switch
        {
            "error" => 0,
            "warning" => 1,
            _ => 2
        };
    }

    private static string NormalizePath(string path)
    {
        return path.Replace('\\', '/');
    }
}
